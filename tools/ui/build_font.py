"""Prepare the repository UI fonts at development time; no font conversion runs during gameplay.

build_font.py <DejaVuSans.ttf> <LICENSE>
    The interface font every Latin-script language draws with (Content/Fonts/UI.spritefont).
build_font.py --language <code> <font> <LICENSE>
    A language whose script the interface font lacks (Chinese, Japanese): Content/Fonts/UI-<code>.spritefont from that
    font, with the Latin ranges, every other character the language's texts use and those its players commonly type.
"""

import argparse
import json
import shutil
import xml.etree.ElementTree as ElementTree
from pathlib import Path

from fontTools.ttLib import TTFont

# Latin, Latin-1, Latin Extended-A and general punctuation, the Vietnamese letters (the horned O and U of Latin
# Extended-B and the toned vowels of Latin Extended Additional) and the four arrows the help's key list draws: the
# game's languages are Latin-script.
RANGES = [(32, 126), (160, 383), (416, 417), (431, 432), (7840, 7929), (8192, 8303), (8592, 8595)]
# The bake's size in points (the pipeline rasterizes at 96 dpi): twice the reference's 14-pixel text, drawn at half
# scale (HudPainter.TextScale), so the text stays sharp at an interface scale of two.
BAKE_POINTS = 21
ROOT = Path(__file__).resolve().parents[2]
FONTS = ROOT / "assets/Hud/Fonts"
CONTENT = ROOT / "Client/PristonTale/Content/Fonts"


def regions_of(values):
    regions = []
    for value in sorted(values):
        if regions and value == regions[-1][1] + 1:
            regions[-1][1] = value
        else:
            regions.append([value, value])
    return regions


def write_spritefont(path, font_file, regions):
    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        '<!-- Generated by tools/ui/build_font.py; baked glyphs avoid runtime font rasterization. -->',
        '<XnaContent xmlns:Graphics="Microsoft.Xna.Framework.Content.Pipeline.Graphics">',
        '  <Asset Type="Graphics:FontDescription">',
        f'    <FontName>../../../../assets/Hud/Fonts/{font_file}</FontName>',
        f'    <Size>{BAKE_POINTS}</Size>',
        '    <Spacing>0</Spacing>',
        '    <UseKerning>true</UseKerning>',
        '    <Style>Regular</Style>',
        '    <DefaultCharacter>?</DefaultCharacter>',
        '    <CharacterRegions>',
    ]
    for start, end in regions:
        lines.extend([
            '      <CharacterRegion>',
            f'        <Start>&#{start};</Start>',
            f'        <End>&#{end};</End>',
            '      </CharacterRegion>',
        ])
    lines.extend(['    </CharacterRegions>', '  </Asset>', '</XnaContent>', ''])
    with open(path, 'w', encoding='utf-8', newline='\n') as output:
        output.write('\n'.join(lines))


# Every character a language's texts use: its client phrases and data texts, its text files and its world catalog.
def language_characters(language):
    texts = []
    localization = ROOT / "Client/PristonTale.Gameplay/Localization"
    for resx in (localization / f"ClientText.{language}.resx", localization / f"DataText.{language}.resx"):
        texts.extend(value.text or '' for value in ElementTree.parse(resx).iter('value'))
    for file in sorted((ROOT / "Client/PristonTale/Texts" / language).rglob('*')):
        if file.is_file():
            texts.append(file.read_text(encoding='utf-8'))
    translations = ROOT / "tools/PristonTale.WorldImport/Translations" / f"{language}.json"
    if translations.exists():
        texts.append(json.dumps(json.loads(translations.read_text(encoding='utf-8')), ensure_ascii=False))
    return {ord(character) for text in texts for character in text if ord(character) >= 32}


# The characters a language's players commonly type, beyond what its texts use, as double-byte rows of a national
# character set: for Simplified Chinese the GB2312 set's full-width punctuation and forms (rows 1 and 3) and its first
# level of 3755 common characters (rows 16 to 55); for Japanese the JIS X 0208 set's punctuation, full-width forms, kana
# (rows 1 to 5) and its first level of 2965 kanji (rows 16 to 47).
COMMON_ROWS = {
    'zh-CN': ('gb2312', [0xA1, 0xA3, *range(0xB0, 0xD8)]),
    'ja': ('euc_jp', [0xA1, 0xA3, 0xA4, 0xA5, *range(0xB0, 0xD0)]),
}


def common_characters(language):
    if language not in COMMON_ROWS:
        return set()
    encoding, rows = COMMON_ROWS[language]
    characters = set()
    for row in rows:
        for cell in range(0xA1, 0xFF):
            try:
                characters.add(ord(bytes([row, cell]).decode(encoding)))
            except UnicodeDecodeError:
                pass
    return characters


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--language", help="a language code whose own font this builds (zh-CN, ja)")
    parser.add_argument("font", type=Path, help="DejaVuSans.ttf, or the language's font")
    parser.add_argument("license", type=Path, help="the font's license")
    arguments = parser.parse_args()
    FONTS.mkdir(parents=True, exist_ok=True)
    cmap = TTFont(arguments.font, fontNumber=0).getBestCmap()
    if arguments.language is None:
        shutil.copyfile(arguments.font, FONTS / "DejaVuSans.ttf")
        shutil.copyfile(arguments.license, FONTS / "DejaVu-LICENSE.txt")
        supported = {value for start, end in RANGES for value in range(start, end + 1) if value in cmap}
        write_spritefont(CONTENT / 'UI.spritefont', 'DejaVuSans.ttf', regions_of(supported))
        return

    shutil.copyfile(arguments.font, FONTS / arguments.font.name)
    shutil.copyfile(arguments.license, FONTS / "NotoSansCJK-LICENSE.txt")
    latin = {value for start, end in RANGES for value in range(start, end + 1)}
    # MonoGame's font description holds characters of the Basic Multilingual Plane only.
    texts = language_characters(arguments.language) | common_characters(arguments.language)
    wanted = {value for value in latin | texts if value <= 0xFFFF}
    missing = sorted(value for value in wanted - latin if value not in cmap)
    if missing:
        print('The font lacks: ' + ' '.join(f'U+{value:04X}' for value in missing))
    write_spritefont(CONTENT / f'UI-{arguments.language}.spritefont', arguments.font.name,
                     regions_of(value for value in wanted if value in cmap))


if __name__ == "__main__":
    main()
