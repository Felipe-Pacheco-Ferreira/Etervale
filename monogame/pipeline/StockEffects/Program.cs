using System.Globalization;
using System.Text;
using MonoGame.Effect;

// The browser runtime's stock effects, from monogame/runtime/src/webgpu/effects (found from this project's folder), each
// written as <name>.wgpu.mgfxo.h beside its source. The exit code is the number of effects that failed.
var effects = Path.GetFullPath(Path.Combine(AppContext.BaseDirectory, "..", "..", "..", "..", "..", "runtime", "src", "webgpu", "effects"));
if (!Directory.Exists(effects))
{
    Console.Error.WriteLine($"No stock effects folder at {effects}.");
    return 1;
}

var failed = 0;
foreach (var source in Directory.GetFiles(effects, "*.fx").Order(StringComparer.Ordinal))
{
    var name = Path.GetFileNameWithoutExtension(source);
    var header = Path.Combine(effects, name + ".wgpu.mgfxo.h");
    var options = EffectCompiler.WebGpuOptions(source, Path.Combine(Path.GetTempPath(), name + ".mgfxo"), false, null);
    var output = new ConsoleOutput();
    try
    {
        var result = EffectCompiler.Parse(options, output);
        var bytes = EffectCompiler.Compile(result, options, out var warnings);
        if (warnings.Length > 0)
        {
            Console.Error.Write(warnings);
        }

        File.WriteAllText(header, Header(name, bytes), new UTF8Encoding(false));
        Console.WriteLine($"{name}: {bytes.Length} bytes -> {header}");
    }
    catch (Exception exception) when (exception is ShaderCompilerException or InvalidOperationException or IOException)
    {
        Console.Error.WriteLine($"{name}: {exception.Message}");
        failed++;
    }
}

return failed;

// The layout of upstream's generated headers (the *.vk.mgfxo.h of the Vulkan runtime), so MG_BUILTIN_EFFECT_* reads both.
static string Header(string name, byte[] bytes)
{
    var symbol = name + "_wgpu_mgfxo";
    var text = new StringBuilder();
    text.Append("// Generated by monogame/pipeline/StockEffects from ").Append(name).Append(".fx (profile WebGPU, MGFX ")
        .Append(EffectCompiler.MgfxVersion.ToString(CultureInfo.InvariantCulture)).Append("). Do not edit.\n\n");
    text.Append("#ifndef ").Append(symbol.ToUpperInvariant()).Append("_H\n#define ").Append(symbol.ToUpperInvariant()).Append("_H\n\n");
    text.Append("static const unsigned char ").Append(symbol).Append("[] = {\n");
    for (var i = 0; i < bytes.Length; i++)
    {
        text.Append(i % 12 == 0 ? "\t" : " ").Append("0x").Append(bytes[i].ToString("x2", CultureInfo.InvariantCulture)).Append(',');
        if (i % 12 == 11 || i == bytes.Length - 1)
        {
            text.Append('\n');
        }
    }

    text.Append("};\n\n#endif\n");
    return text.ToString();
}

internal sealed class ConsoleOutput : IEffectCompilerOutput
{
    public void WriteWarning(string file, int line, int column, string message) => Console.Error.WriteLine($"{file}({line},{column}): warning: {message}");

    public void WriteError(string file, int line, int column, string message) => Console.Error.WriteLine($"{file}({line},{column}): error: {message}");
}
